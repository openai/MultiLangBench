PRAGMA page_size=1024;
PRAGMA auto_vacuum=NONE;
BEGIN;
CREATE TABLE t1(a PRIMARY KEY, b UNIQUE);
WITH RECURSIVE c(a) AS (VALUES(1) UNION ALL SELECT a+1 FROM c WHERE a<128) INSERT INTO t1 SELECT a, CAST(printf('%0400d',a) AS BLOB) FROM c;
CREATE TABLE t2(a PRIMARY KEY, b UNIQUE);
INSERT INTO t2 SELECT * FROM t1;
COMMIT;
DELETE FROM t1 WHERE a%2;
INSERT INTO t1 SELECT b, a FROM t2 WHERE a%2;
UPDATE t1 SET b=CAST(printf('%0600d',a) AS BLOB) WHERE (a%2)==0;